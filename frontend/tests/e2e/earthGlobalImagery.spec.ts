import {test,expect} from '@playwright/test'
for(const mobile of [false,true])test(`C6-1A source ownership, terminal fallback and camera preservation ${mobile?'mobile':'desktop'}`,async({page})=>{
 test.setTimeout(90000)
 await page.setViewportSize(mobile?{width:390,height:844}:{width:1440,height:900})
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 await page.route('https://**/*',route=>route.fulfill({status:403,body:'Declared permission failure fixture'}))
 await page.route('**/api/earth/**',route=>route.fulfill({status:503,body:'Declared unavailable fixture'}))
 await page.goto('/earth-runtime/?orasProof=1')
 await expect(page.locator('#earth')).toHaveAttribute('data-status','ready')
 await expect.poll(()=>page.evaluate(()=>(window as any).orasEarthDiagnostics()?.imagery?.actual),{timeout:25000}).toBe('local')
 const before=await page.evaluate(()=>(window as any).orasEarthDiagnostics().cameraHeightM)
 await page.selectOption('#imagery-source','local')
 const diag=await page.evaluate(()=>(window as any).orasEarthDiagnostics())
 expect(diag.imagery.localAllocations).toBe(1);expect(diag.imagery.managedLayers).toBe(0);expect(diag.imagery.labelsLayers).toBe(0);expect(diag.imagery.budget.active).toBe(0);expect(diag.imagery.ionSessionRequests).toBe(0);expect(diag.cameraHeightM).toBe(before)
 await expect(page.locator('[value="ion"]')).toBeDisabled()
 await expect(page.locator('#viewer canvas')).toHaveAttribute('data-skybox','ready')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 expect(errors).toEqual([])
})
test('actual upstream OSM factory, cached switching and separately owned labels keep truthful layer order',async({page})=>{
 test.setTimeout(60000)
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 const image=Buffer.from(await page.evaluate(()=>{const canvas=document.createElement('canvas');canvas.width=canvas.height=256;const context=canvas.getContext('2d')!;context.fillStyle='#567854';context.fillRect(0,0,256,256);return canvas.toDataURL('image/png').split(',')[1]}),'base64')
 await page.route('https://**/*',route=>route.fulfill({status:200,contentType:'image/png',body:image}))
 await page.route('**/api/earth/**',route=>route.fulfill({status:503,body:'Declared unavailable fixture'}))
 await page.goto('/earth-runtime/?orasProof=1')
 await expect(page.locator('#earth')).toHaveAttribute('data-status','ready')
 await page.selectOption('#imagery-source','osm')
 await expect.poll(()=>page.evaluate(()=>(window as any).orasEarthDiagnostics().imagery.actual)).toBe('osm')
 await expect.poll(()=>page.evaluate(()=>(window as any).orasEarthDiagnostics().imagery.sources.osm.loaded),{timeout:15000}).toBeGreaterThan(0)
 await page.evaluate(()=>(window as any).orasEarthProofView({lon:2.3522,lat:48.8566,height:100000}))
 await page.selectOption('#imagery-source','eox-2016')
 await page.locator('#imagery-labels').check()
 await expect.poll(()=>page.evaluate(()=>(window as any).orasEarthProofState().imageryOrder)).toEqual(['local','eox-2016','labels'])
 const before=await page.evaluate(()=>(window as any).orasEarthDiagnostics().imagery)
 expect(before.sources.osm.paused).toBe(true)
 await page.evaluate(()=>(window as any).orasEarthProofView({lon:2.3522,lat:48.8566,height:50000}))
 await page.waitForTimeout(600)
 const after=await page.evaluate(()=>(window as any).orasEarthDiagnostics().imagery)
 expect(after.selected).toBe('eox-2016');expect(after.sources.osm.requested).toBe(before.sources.osm.requested);expect(after.localAllocations).toBe(1);expect(after.managedLayers).toBe(1);expect(after.ionSessionRequests).toBe(0)
 await page.locator('#imagery-labels').uncheck()
 expect(await page.evaluate(()=>(window as any).orasEarthProofState().imageryOrder)).toEqual(['local','eox-2016'])
 expect(errors).toEqual([])
})
test('C6-1A five genuine runtime destruction/recreation cycles retain one base per viewer',async({page})=>{
 test.setTimeout(120000)
 await page.route('https://**/*',route=>route.abort())
 await page.route('**/api/earth/**',route=>route.fulfill({status:503,body:'Declared unavailable fixture'}))
 for(let i=0;i<5;i++){
  await page.goto('/earth-runtime/?orasProof=1')
  await expect(page.locator('#earth')).toHaveAttribute('data-status','ready')
  await expect.poll(()=>page.evaluate(()=>(window as any).orasEarthDiagnostics()?.imagery?.localAllocations)).toBe(1)
  if(i===0)await page.selectOption('#imagery-source','local')
  await expect(page.locator('#imagery-source')).toHaveValue('local')
  expect(await page.evaluate(()=>(window as any).orasEarthProofState().imageryOrder)).toEqual(['local'])
  await page.goto('about:blank')
 }
})
