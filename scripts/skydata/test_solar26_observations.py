"""Offline regressions: source semantics, missing samples and bounded acquisition."""
import importlib.util
import io
import math
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

SPEC = importlib.util.spec_from_file_location("observations", Path(__file__).with_name("acquire_solar26_observations.py"))
obs = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(obs)


class ObservationsTest(unittest.TestCase):
    def test_ibex_bins_are_cells_not_duplicate_seam_or_pole_samples(self):
        flux = [[1.0]*60 for _ in range(30)]
        flux[0][0], flux[-1][-1] = 7.0, 11.0
        data = obs.map_data(flux, [[4.0]*60 for _ in range(30)])
        self.assertEqual(data["longitude_deg"], list(range(3, 360, 6)))
        self.assertEqual(data["latitude_deg"], list(range(-87, 90, 6)))
        self.assertEqual((data["flux"][0][0], data["flux"][-1][-1]), (7, 11))
        self.assertEqual(data["uncertainty"][0][0], 2)
        # Integrate the bin solid angles independently: cover exactly 4*pi,
        # without a seam overlap or singular duplicated pole measurement.
        total = sum(math.radians(6)*(math.sin(math.radians(lat+3))-math.sin(math.radians(lat-3)))
                    for lat in data["latitude_deg"] for _ in data["longitude_deg"])
        self.assertAlmostEqual(total, 4*math.pi, places=12)

    def test_invalid_map_cells_are_null_not_interpolated(self):
        flux, variance = [[1.0]*60 for _ in range(30)], [[4.0]*60 for _ in range(30)]
        flux[0][0], flux[0][1], variance[0][2], flux[0][3] = math.nan, -999, -1, math.inf
        data = obs.map_data(flux, variance)
        self.assertEqual(data["flux"][0][:5], [None, None, None, None, 1])
        self.assertEqual(data["uncertainty"][0][:5], [None, None, None, None, 2])
        self.assertEqual(data["mask"][0][:5], [True, True, True, True, False])
        obs.encode(data)  # Strict JSON has no NaN or infinity.
        with self.assertRaises(ValueError):
            obs.map_data(flux[:-1], variance)

    def test_ibex_parser_fails_closed_on_frame_energy_units_and_shape(self):
        header = "# 28:30x60:\n# skyframe=ECLIPJ2000 posframe=J2000\n# min_0=-90 max_0=90 num_0=30\n# min_1=0 max_1=360 num_1=60\n# e_approx='2.73' hs_radius='1' no_cg_xform='0' fe_method='spwloglog'\n# h_title='Flux (#/cm^2 s sr keV)'\n"
        raw = (header + (" ".join(["2"]*60)+"\n")*30).encode()
        self.assertEqual(obs.parse_ibex_matrix(raw)[29][59], 2)
        for old, new in [(b"ECLIPJ2000", b"J2000"), (b"2.73", b"0.71"), (b"cm^2", b"m^2"), (b"num_0=30", b"num_0=31"), (b"hs_radius='1'", b"hs_radius='100'")]:
            with self.subTest(old=old), self.assertRaises(ValueError):
                obs.parse_ibex_matrix(raw.replace(old, new))
        with self.assertRaises(ValueError):
            obs.parse_ibex_matrix(raw.rsplit(b"\n", 2)[0])

    def test_j2000_transform_against_independent_cspice_n0067(self):
        # Generated by spiceypy8.0.0/CSPICE_N0067 pxform(ECLIPJ2000,J2000,0)
        # applied to latrec, independently of this script's obliquity rotation.
        cases = [(0, 0, [1, 0, 0]),
                 (90, 0, [0, 0.9174820620691818, 0.3977771559319137]),
                 (0, 90, [0, -0.3977771559319137, 0.9174820620691818]),
                 (3, -87, [0.05226423163382687, 0.3997450475311582, -0.9151351523496613]),
                 (357, 87, [0.05226423163382687, -0.39974504753115825, 0.9151351523496613]),
                 (267, 33, [-0.043892626146236964, -0.9850556431160699, 0.16654974432635])]
        for lon, lat, expected in cases:
            result = obs.ecliptic_direction_j2000(lon, lat)
            for actual, reference in zip(result, expected):
                self.assertAlmostEqual(actual, reference, places=14)
            self.assertAlmostEqual(sum(v*v for v in result), 1, places=14)
        with self.assertRaises(ValueError):
            obs.ecliptic_direction_j2000(0, 91)

    def test_minute_statistics_quality_and_gaps_are_not_measurement_uncertainty(self):
        data = obs.aggregate_minutes([0, 500_000_000, 1_000_000_000, 120_000_000_000],
                                     [3, 5, 100, 9], [0, 0, 1, 0], [0, 0, 4, 0], 0)
        self.assertEqual(data["value"][:3], [4, None, 9])
        self.assertEqual(data["minimum"][:3], [3, None, 9])
        self.assertEqual(data["maximum"][:3], [5, None, 9])
        self.assertEqual(data["count"][:3], [2, 0, 1])
        self.assertEqual(data["rejected_count"][:3], [1, 0, 0])
        self.assertEqual(data["quality_bitmask"][:3], [4, 0, 0])
        self.assertEqual(len(data["time_utc"]), 1440)
        self.assertEqual(data["time_utc"][-1], "1970-01-01T23:59:00Z")

    def test_fill_range_nonfinite_and_nonzero_bitmask_are_excluded(self):
        data = obs.aggregate_minutes(list(range(6)), [-1e31, math.nan, 100001, math.inf, 7, 8], [0]*6, [0, 0, 0, 0, 2, 0], 0)
        self.assertEqual(data["value"][0], 8)
        self.assertEqual(data["count"][0], 1)
        self.assertEqual(data["rejected_count"][0], 5)

    def test_unsupported_epoch_order_shape_or_cadence_rejected(self):
        for epochs in [[-1], [86400_000_000_000], [1, 0], [0, 0], list(range(121))]:
            with self.subTest(epochs=epochs[:3]), self.assertRaises(ValueError):
                obs.aggregate_minutes(epochs, [1]*len(epochs), [0]*len(epochs), [0]*len(epochs), 0)
        with self.assertRaises(ValueError):
            obs.aggregate_minutes([0], [], [0], [0], 0)

    def test_immutable_release_and_strict_json(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory)/"product.json"
            obs.immutable_write(path, b"a")
            obs.immutable_write(path, b"a")
            with self.assertRaises(ValueError):
                obs.immutable_write(path, b"b")
            self.assertEqual(path.read_bytes(), b"a")
        with self.assertRaises(ValueError):
            obs.encode({"value": math.nan})

    def test_pinned_cache_refuses_corrupt_source_without_network(self):
        with tempfile.TemporaryDirectory() as directory:
            acquisition = obs.Acquisition(directory)
            name = next(iter(obs.SOURCES))
            with self.assertRaises(FileNotFoundError):
                acquisition.get(name)
            (Path(directory)/name).write_bytes(b"corrupt")
            with self.assertRaises(ValueError):
                acquisition.get(name)

    def test_streamed_source_limit_and_failed_probe_are_preserved(self):
        class Response(io.BytesIO):
            headers = {}  # The server omits Content-Length.
            def geturl(self):
                return "https://spdf.gsfc.nasa.gov/tiny.txt"
        with tempfile.TemporaryDirectory() as directory, patch.dict(obs.SOURCES, {"tiny.txt": ("https://spdf.gsfc.nasa.gov/", obs.sha256(b"123"), 3, "ibex")}):
            acquisition = obs.Acquisition(directory)
            with patch.object(obs, "urlopen", return_value=Response(b"1234")), self.assertRaises(ValueError):
                acquisition.get("tiny.txt", download=True)
            self.assertEqual(acquisition.state["transferred"], 4)
            self.assertEqual(acquisition.state["attempts"][0]["status"], "failed")
            self.assertFalse((Path(directory)/"tiny.txt").exists())


if __name__ == "__main__":
    unittest.main()
